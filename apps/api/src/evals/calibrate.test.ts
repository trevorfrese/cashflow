import { describe, expect, it } from 'vitest';

import { buildPdTable, poolMonotonic, renderPdTable } from './calibrate.ts';
import { makeCustomer } from './fixtures.ts';
import type { CustomerResult } from './portfolio.ts';

const source = {
  applicants: 100,
  seeds: ['test'],
  horizonMonths: 12,
  servicingPolicy: 'standard',
  badDefinition: 'test',
  note: 'unit test',
};

/** `plans` funded customers at `score`, of which `bad` went bad and lost half a month's rent. */
function band(score: number, plans: number, bad: number): CustomerResult[] {
  return Array.from({ length: plans }, (_, i) =>
    makeCustomer({
      applicantId: `${score}-${i}`,
      score,
      payoutCount: 10,
      payoutCents: 1_000_000,
      planRentCents: 100_000,
      bad: i < bad,
      chargedOffCents: i < bad ? 50_000 : 0,
      recoveredCents: i < bad ? 5_000 : 0,
    }),
  );
}

describe('PD calibration', () => {
  it('measures the bad rate of each five point band and covers 0 to 100', () => {
    const table = buildPdTable([...band(52, 10, 3), ...band(63, 20, 2), ...band(97, 50, 1)], {
      minScore: 50,
      bandWidth: 5,
      source,
    });
    expect(table.bands).toEqual([
      { minScore: 0, maxScore: 49, pdBps: 3000, plans: 0, bad: 0 },
      { minScore: 50, maxScore: 54, pdBps: 3000, plans: 10, bad: 3 },
      { minScore: 60, maxScore: 64, pdBps: 1000, plans: 20, bad: 2 },
      { minScore: 95, maxScore: 100, pdBps: 200, plans: 50, bad: 1 },
    ]);
    // Net loss on a bad plan: 45,000 of a 100,000 rent, rounded up to the next 5 points.
    expect(table.measuredLossGivenDefaultBps).toBe(4500);
    expect(table.measuredPeriodsPerPlan).toBe(10);
    expect(table.source).toEqual(source);
  });

  it('pools neighboring bands so PD never rises with score', () => {
    const pooled = poolMonotonic([
      { minScore: 50, maxScore: 54, plans: 100, bad: 10, pdBps: 0 },
      { minScore: 55, maxScore: 59, plans: 100, bad: 14, pdBps: 0 },
      { minScore: 60, maxScore: 64, plans: 100, bad: 5, pdBps: 0 },
    ]);
    expect(pooled).toEqual([
      { minScore: 50, maxScore: 59, plans: 200, bad: 24, pdBps: 1200 },
      { minScore: 60, maxScore: 64, plans: 100, bad: 5, pdBps: 500 },
    ]);
  });

  it('ignores applicants who were never funded', () => {
    const table = buildPdTable(
      [...band(70, 10, 1), makeCustomer({ applicantId: 'declined', score: 70, payoutCount: 0 })],
      { minScore: 50, bandWidth: 5, source },
    );
    expect(table.bands.find((b) => b.minScore === 70)).toMatchObject({ plans: 10, bad: 1 });
  });

  it('renders a module the pricing code can import', () => {
    const table = buildPdTable(band(80, 10, 1), { minScore: 50, bandWidth: 5, source });
    const text = renderPdTable(table, 'PD_TABLE_V2', 'cashflow-v2');
    expect(text).toContain('export const PD_TABLE_V2: PdTable = {');
    expect(text).toContain('GENERATED by');
    expect(text).not.toContain(String.fromCharCode(0x2014));
  });
});
