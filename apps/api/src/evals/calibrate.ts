/**
 * Regenerates the PD table the pricing module reads.
 *
 *   pnpm --filter @cashflow/api eval:calibrate
 *   pnpm --filter @cashflow/api eval:calibrate --n 10000 --seeds calibration-1,calibration-2
 *   pnpm --filter @cashflow/api eval:calibrate --dry-run     # print, do not write
 *
 * Runs the current credit policy under the standard servicing policy on a large synthetic
 * population, groups funded plans into five point score bands, and measures the share of each
 * band that went bad. Bands are then pooled where needed so that PD never rises with score.
 * The result is written to `src/underwriting/pd-table.ts` with the run parameters.
 *
 * The seeds are deliberately not the ones the gates are judged on, so pricing is not fitted
 * to the same applicants it is evaluated against. Rerun this whenever the scorecard, the
 * cutoffs, or the servicing policy change, and give the policy a new version.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { STANDARD_SERVICING_POLICY } from '../servicing/policy.ts';
import { decide } from '../underwriting/engine.ts';
import type { PdBand, PdTable } from '../underwriting/pd-table.ts';
import { CURRENT_POLICY } from '../underwriting/policy.ts';
import { ASSUMPTIONS } from './assumptions.ts';
import { drawPopulation } from './population.ts';
import { runPortfolio, type CustomerResult } from './portfolio.ts';

export const CALIBRATION_DEFAULTS = {
  n: 10_000,
  seeds: ['calibration-1', 'calibration-2'],
  bandWidth: 5,
};

/** Pool neighboring bands until the bad rate never rises as the score rises. */
export function poolMonotonic(bands: PdBand[]): PdBand[] {
  const out: PdBand[] = [];
  for (const band of bands) {
    out.push({ ...band });
    // A higher band with a higher bad rate than the one below it is merged into it.
    while (out.length >= 2) {
      const upper = out[out.length - 1]!;
      const lower = out[out.length - 2]!;
      if (upper.bad * lower.plans <= lower.bad * upper.plans) break;
      out.splice(out.length - 2, 2, {
        minScore: lower.minScore,
        maxScore: upper.maxScore,
        plans: lower.plans + upper.plans,
        bad: lower.bad + upper.bad,
        pdBps: 0,
      });
    }
  }
  return out.map((b) => ({
    ...b,
    pdBps: b.plans === 0 ? 0 : Math.round((b.bad * 10_000) / b.plans),
  }));
}

export function buildPdTable(
  customers: readonly CustomerResult[],
  options: { minScore: number; bandWidth: number; source: PdTable['source'] },
): PdTable {
  const funded = customers.filter((c) => c.payoutCount > 0 && c.score !== null);
  const raw: PdBand[] = [];
  for (let lo = options.minScore; lo <= 100; lo += options.bandWidth) {
    // The top band takes 100 with it.
    const hi = lo + options.bandWidth >= 100 ? 100 : lo + options.bandWidth - 1;
    const inBand = funded.filter((c) => c.score! >= lo && c.score! <= hi);
    raw.push({
      minScore: lo,
      maxScore: hi,
      plans: inBand.length,
      bad: inBand.filter((c) => c.bad).length,
      pdBps: 0,
    });
    if (hi === 100) break;
  }
  const pooled = poolMonotonic(raw.filter((b) => b.plans > 0));
  // Scores under the cutoff are never funded, so nothing can be measured there. They are
  // given the PD of the riskiest measured band, which is a floor on their risk.
  const riskiest = pooled[0]!;
  const bands: PdBand[] = [
    ...(riskiest.minScore > 0
      ? [{ minScore: 0, maxScore: riskiest.minScore - 1, pdBps: riskiest.pdBps, plans: 0, bad: 0 }]
      : []),
    ...pooled,
  ];
  bands[bands.length - 1]!.maxScore = 100;

  const bad = funded.filter((c) => c.bad);
  const netLoss = bad.reduce((sum, c) => sum + c.chargedOffCents - c.recoveredCents, 0);
  const rentAtRisk = bad.reduce((sum, c) => sum + c.planRentCents, 0);
  const periods = funded.reduce((sum, c) => sum + c.payoutCount, 0);
  return {
    bands,
    // Rounded up to the next 5 points so pricing errs on the side of charging for risk.
    measuredLossGivenDefaultBps:
      rentAtRisk === 0 ? 10_000 : Math.ceil((netLoss * 10_000) / rentAtRisk / 500) * 500,
    measuredPeriodsPerPlan:
      funded.length === 0 ? 1 : Math.round((periods / funded.length) * 10) / 10,
    source: options.source,
  };
}

export function renderPdTable(table: PdTable, exportName: string, version: string): string {
  return `/**
 * Probability of default by score band for policy ${version}.
 *
 * GENERATED by \`pnpm --filter @cashflow/api eval:calibrate\`. Do not edit by hand: rerun the
 * command and commit the result together with a new policy version.
 */

export interface PdBand {
  /** Lowest score in the band, inclusive. */
  minScore: number;
  /** Highest score in the band, inclusive. */
  maxScore: number;
  /** Share of funded plans in the band that went bad within the horizon, in basis points. */
  pdBps: number;
  /** Funded plans behind the estimate. */
  plans: number;
  /** Plans that went bad. */
  bad: number;
}

export interface PdTable {
  /** Bands from the lowest scores to the highest. Together they cover 0 to 100. */
  bands: readonly PdBand[];
  /** Net loss on a bad plan as a share of one month's rent, measured in the same run. */
  measuredLossGivenDefaultBps: number;
  /** Average funded periods per plan in the same run. */
  measuredPeriodsPerPlan: number;
  /** The run that produced the table. */
  source: {
    applicants: number;
    seeds: readonly string[];
    horizonMonths: number;
    servicingPolicy: string;
    badDefinition: string;
    note: string;
  };
}

export const ${exportName}: PdTable = ${JSON.stringify(table, null, 2)};
`;
}

function main(argv: string[]) {
  const value = (flag: string): string | undefined => {
    const idx = argv.indexOf(flag);
    return idx === -1 ? undefined : argv[idx + 1];
  };
  const n = Number(value('--n') ?? CALIBRATION_DEFAULTS.n);
  const seeds = (value('--seeds') ?? CALIBRATION_DEFAULTS.seeds.join(',')).split(',');
  if (!Number.isInteger(n) || n < 1) throw new Error('--n must be a positive integer');
  const policy = CURRENT_POLICY;
  const customers: CustomerResult[] = [];
  for (const seed of seeds) {
    const result = runPortfolio(drawPopulation({ n, seed }), {
      label: `calibration/${seed}`,
      decide: (input) => decide(input, policy),
      servicing: STANDARD_SERVICING_POLICY,
      exposure: policy.exposure,
    });
    customers.push(...result.customers);
  }
  const table = buildPdTable(customers, {
    minScore: policy.minScore,
    bandWidth: CALIBRATION_DEFAULTS.bandWidth,
    source: {
      applicants: n * seeds.length,
      seeds,
      horizonMonths: ASSUMPTIONS.horizonMonths,
      servicingPolicy: STANDARD_SERVICING_POLICY.name,
      badDefinition: `any installment ${ASSUMPTIONS.badDaysPastDue} days past due, or written off`,
      note: `Synthetic population (src/evals/population.ts), base case, policy ${policy.version}. Not real outcomes.`,
    },
  });
  const lines = table.bands.map(
    (b) =>
      `  ${String(b.minScore).padStart(3)}-${String(b.maxScore).padEnd(3)}  plans ${String(b.plans).padStart(5)}  bad ${String(b.bad).padStart(4)}  PD ${(b.pdBps / 100).toFixed(1)}%`,
  );
  process.stdout.write(
    [
      `PD table for ${policy.version}: ${n} applicants x seeds ${seeds.join(', ')}`,
      ...lines,
      `  loss given default ${table.measuredLossGivenDefaultBps / 100}% of a month's rent, ${table.measuredPeriodsPerPlan} periods per plan`,
      '',
    ].join('\n'),
  );
  if (argv.includes('--dry-run')) return;
  const target = fileURLToPath(new URL('../underwriting/pd-table.ts', import.meta.url));
  writeFileSync(target, renderPdTable(table, 'PD_TABLE_V2', policy.version));
  process.stdout.write(`Wrote ${target}\n`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main(process.argv.slice(2));
}
